import { access, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = (name) => readFile(path.join(root, name), 'utf8');
const dictionary = (await read('config/urdu.js')).replace('export const urdu', 'const urdu');
const photoDictionary = (await read('config/urdu-photos.js')).replace(
  'export const urduPhotos',
  'const urduPhotos',
);
const localizer = (await read('src/localization.js'))
  .replace(/^import .*;\r?\n/gm, '')
  .replace(/^export /gm, '');
const css = `
html[lang='ur'] body.guestbook, html[lang='ur'] body { font-family:'Noto Naskh Arabic',serif; line-height:1.95; }
html[lang='ur'] :is(h1,h2,h3,.guestbook .form-panel h2) { font-family:'Noto Nastaliq Urdu','Noto Naskh Arabic',serif; line-height:2; font-size:30px; }
html[lang='ur'] :is(.eyebrow,.note,.label,button,input,textarea,select,.byline,.status,.field,.button,.photo-state,.photo-destination,footer,.awake-control,.photo-name,.remove-photo,.text-button) { font-family:'Noto Naskh Arabic',serif !important; letter-spacing:0 !important; line-height:1.95; font-size:16px; }
html[lang='ur'] .guestbook .wish { border-left:1px solid var(--line); border-right:3px solid #987555; }
html[lang='ur'] .guestbook .toolbar .note { max-width:26ch; }
html[lang='ur'] .photo-name { direction:ltr; unicode-bidi:isolate; }
`;
function bundle(photos) {
  return `<!-- Generated by npm run sync:locales. Edit config/urdu*.js and src/localization.js. -->\n<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Noto+Naskh+Arabic:wght@400;500&amp;family=Noto+Nastaliq+Urdu:wght@400;500&amp;display=swap" />\n<style>${css}</style>\n<script>\n(() => {\n${dictionary}\n${photos ? photoDictionary : ''}\n${localizer}\nconst language = languageFrom(${photos ? 'CONFIG' : 'PAGE'}.language);\ndocument.documentElement.lang = language;\ndocument.documentElement.dir = language === 'ur' ? 'rtl' : 'ltr';\nconst localizer = createGuestLocalizer(document.body, { language, extra: ${photos ? 'urduPhotos' : '{}'} });\nwindow.guestTranslate = (value) => localizer.translate(value);\n})();\n</script>\n`;
}
for (const [folder, photos] of [
  ['backend/google-wishes', false],
  ['backend/google-photos', true],
]) {
  await mkdir(path.join(root, folder), { recursive: true });
  await writeFile(path.join(root, folder, 'GuestLocale.html'), bundle(photos));
}
// Refresh the private uploader's generated locale and combined deployment file
// when its owner-maintained source is available. Never rewrite its source files.
const photoFolder = path.join(root, '.local/google-photos');
const preparePath = path.join(photoFolder, 'prepare.mjs');
let hasPhotoSource = true;
try {
  await access(preparePath);
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  hasPhotoSource = false;
}
if (hasPhotoSource) {
  await writeFile(path.join(photoFolder, 'GuestLocale.html'), bundle(true));
  await import(pathToFileURL(preparePath).href);
  console.log(
    'Guest locale bundles generated; combined photo Code.gs ready in .preview/google-photos/.',
  );
} else {
  console.log(
    'Guest locale bundles generated. Follow docs/urdu-setup.md for the separate uploader.',
  );
}
